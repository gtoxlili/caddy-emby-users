#!/usr/bin/env python3
"""Regenerates the web client's display face, Smiley Sans (SIL OFL), as unicode-range slices.

Smiley Sans has Reserved Font Names, and a subset is a modified version under the OFL, so
the slices carry their own name, House Display; copyright and license records are kept.

The whole font is 1.1 MB. Titles are arbitrary text, so a fixed subset will not do; instead
the font is cut along the slices Google Fonts uses for Noto Sans SC, which group characters
by frequency. A page downloads only the slices its text touches.

Writes ui/src/assets/display/*.woff2 and ui/src/styles/display.css. Run with:

    uvx --with fonttools --with brotli python scripts/ui_font.py
"""
import io
import pathlib
import re
import shutil
import urllib.request
import zipfile

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "ui/src/assets/display"
CSS = ROOT / "ui/src/styles/display.css"
RELEASE = "https://github.com/atelier-anchor/smiley-sans/releases/download/v2.0.1/smiley-sans-v2.0.1.zip"
SLICES = "https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@700&display=swap"
FAMILY = "House Display"
UA = "Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36"


def fetch(url: str) -> bytes:
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=120).read()


def parse_range(text: str) -> set[int]:
    out: set[int] = set()
    for part in text.split(","):
        part = part.strip().removeprefix("U+").removeprefix("u+")
        lo, _, hi = part.partition("-")
        out.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return out


def to_range(cps: list[int]) -> str:
    spans, start, prev = [], cps[0], cps[0]
    for c in cps[1:] + [None]:
        if c is not None and c == prev + 1:
            prev = c
            continue
        spans.append(f"U+{start:x}" if start == prev else f"U+{start:x}-{prev:x}")
        if c is not None:
            start = prev = c
    return ", ".join(spans)


def main() -> None:
    with zipfile.ZipFile(io.BytesIO(fetch(RELEASE))) as z:
        name = next(n for n in z.namelist() if n.endswith("SmileySans-Oblique.ttf"))
        ttf = z.read(name)
    cmap = set(TTFont(io.BytesIO(ttf)).getBestCmap())
    slices = [parse_range(m) for m in re.findall(r"unicode-range:\s*([^;]+);", fetch(SLICES).decode())]
    covered = set().union(*slices)
    # Characters the font has but Google's slices miss go into one more slice.
    slices.append(cmap - covered)

    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)
    rules, total = [], 0
    for i, wanted in enumerate(slices):
        cps = sorted(wanted & cmap)
        if not cps:
            continue
        font = TTFont(io.BytesIO(ttf))
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.name_IDs = [0, 13, 14]
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=cps)
        sub.subset(font)
        names = font["name"]
        for nid, value in ((1, FAMILY), (2, "Regular"), (3, f"{FAMILY} {i:03d}"), (4, FAMILY), (6, "HouseDisplay")):
            names.setName(value, nid, 3, 1, 0x409)
        buf = io.BytesIO()
        font.flavor = "woff2"
        font.save(buf)
        data = buf.getvalue()
        total += len(data)
        file = f"smiley-{i:03d}.woff2"
        (OUT / file).write_bytes(data)
        rules.append(
            "@font-face {\n"
            f"    font-family: '{FAMILY}';\n"
            f"    src: url('../assets/display/{file}') format('woff2');\n"
            "    font-weight: 400;\n"
            "    font-display: swap;\n"
            f"    unicode-range: {to_range(cps)};\n"
            "}\n"
        )
    header = "/* Generated by scripts/ui_font.py: Smiley Sans renamed House Display, SIL OFL 1.1 (public/OFL.txt). */\n"
    CSS.write_text(header + "".join(rules))
    print(f"{len(rules)} slices, {total} bytes -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
